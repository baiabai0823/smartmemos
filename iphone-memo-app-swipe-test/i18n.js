const LANGUAGE_KEY = "smartmemo.language.v1";
let appLanguage = "zh-CN";
try { appLanguage = localStorage.getItem(LANGUAGE_KEY) === "en" ? "en" : "zh-CN"; } catch {}
function tr(text) {
  if (appLanguage !== "zh-CN") return text;
  if (Object.hasOwn(SMARTMEMO_ZH, text)) return SMARTMEMO_ZH[text];
  const remaining = /^(\d+) (Day|Hour|Minute)s? Left$/.exec(text);
  if (remaining) return `还剩 ${remaining[1]} ${{Day:"天", Hour:"小时", Minute:"分钟"}[remaining[2]]}`;
  return text;
}
function setAppLanguage(language) {
  if (language !== "zh-CN" && language !== "en") return;
  localStorage.setItem(LANGUAGE_KEY, language);
  appLanguage = language;
  document.documentElement.lang = language;
}
document.documentElement.lang = appLanguage;
